#!/usr/bin/env python3
"""Generate the C symbol registration table for statically linked extensions.

The libpglite WASI module is one compilation unit with a hand written
``dlopen``/``dlsym`` shim. Statically linked extensions must have every
SQL-visible symbol registered so PostgreSQL can resolve them. This script
parses the extension SQL files and emits a header included by
``sdk_port-wasi-dlfcn.c``.

A ``CREATE FUNCTION`` may provide an explicit C symbol as the second argument
of ``AS 'MODULE_PATHNAME', 'symbol'``; PostgreSQL calls ``dlsym`` with that
symbol, not with the SQL name. Those aliases must be registered instead.

Usage: gen_extension_symbols.py OUTPUT_HEADER path/to/vector--0.8.0.sql \
           path/to/pg_trgm--1.3.sql path/to/pg_trgm--1.3--1.4.sql ...
"""

from __future__ import annotations

import re
import sys

_STATEMENT_RE = re.compile(
    r"CREATE\s+FUNCTION\s+([a-z_][a-z0-9_]*)\s*\((.*?);",
    re.IGNORECASE | re.DOTALL,
)
_SYMBOL_RE = re.compile(
    r"MODULE_PATHNAME'\s*(?:,\s*'([a-z_][a-z0-9_]*)')?",
    re.IGNORECASE,
)


def symbols_from_sql(text: str) -> set[str]:
    symbols: set[str] = set()
    for match in _STATEMENT_RE.finditer(text):
        sql_name = match.group(1)
        body = match.group(2)
        explicit = _SYMBOL_RE.search(body)
        symbol = sql_name
        if explicit and explicit.group(1):
            symbol = explicit.group(1)
        symbols.add(symbol)
    return symbols


def render(names: list[str]) -> str:
    out: list[str] = []
    out.append("/* Generated by gen_extension_symbols.py; do not edit. */")
    out.append("#define PGLITE_STATIC_EXTENSION_SYMBOLS 1")
    for name in names:
        out.append(f"extern void {name}(void);")
        out.append(f"extern void pg_finfo_{name}(void);")
    out.append(
        "typedef struct { const char *name; void *address; } pglite_symbol_entry;"
    )
    out.append("static const pglite_symbol_entry pglite_extension_symbols[] = {")
    for name in names:
        out.append(f'    {{"{name}", (void *){name}}},')
        out.append(f'    {{"pg_finfo_{name}", (void *)pg_finfo_{name}}},')
    out.append("};")
    out.append("")
    out.append("static void *")
    out.append("pglite_lookup_extension_symbol(const char *symbol)")
    out.append("{")
    out.append(
        "    size_t count = sizeof(pglite_extension_symbols) / "
        "sizeof(pglite_symbol_entry);"
    )
    out.append("    for (size_t i = 0; i < count; i++) {")
    out.append(
        "        if (strcmp(symbol, pglite_extension_symbols[i].name) == 0)"
    )
    out.append("            return pglite_extension_symbols[i].address;")
    out.append("    }")
    out.append("    return NULL;")
    out.append("}")
    out.append("")
    return "\n".join(out)


def main() -> int:
    if len(sys.argv) < 3:
        print(__doc__, file=sys.stderr)
        return 2
    output, sql_paths = sys.argv[1], sys.argv[2:]
    names: set[str] = set()
    for path in sql_paths:
        try:
            text = open(path, encoding="utf-8").read()
        except OSError as exc:
            print(f"cannot read {path}: {exc}", file=sys.stderr)
            return 2
        names.update(symbols_from_sql(text))
    with open(output, "w", encoding="utf-8") as handle:
        handle.write(render(sorted(names)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
