#!/bin/bash
# Install the statically linked extensions for the WASI module and generate
# the dlopen/dlsym symbol registration table.
#
# Runs inside the pglite-build container.  Compilation happens later in
# pglite-wasm/build.sh, where the WASI compiler environment is available; this
# script installs the SQL/control files, creates the .so placeholders that
# PostgreSQL stats before dlopen, copies extension data files, and parses the
# extension SQL to emit the symbol table consumed by
# wasm-build/sdk_port-wasi/sdk_port-wasi-dlfcn.c.
set -e

. wasm-build/extension.sh

SHARE_EXT="${PGROOT}/share/postgresql/extension"
mkdir -p "${SHARE_EXT}" "${PGROOT}/lib/postgresql"

CONTRIB_LIST="${WORKSPACE}/extra/static-extensions.list"
if [ ! -f "${CONTRIB_LIST}" ]; then
    echo "static extension list not found: ${CONTRIB_LIST}"
    exit 20
fi

# pgvector sources are fetched by build/scripts/build-wasi.sh into extra-wasi.
VECTOR=${PG_EXTRA}/vector
[ -d "${VECTOR}/src" ] || VECTOR="${WORKSPACE}/extra/vector"
if [ ! -d "${VECTOR}/src" ]; then
    echo "pgvector sources not found at ${VECTOR}"
    exit 21
fi

touch "${PGROOT}/lib/postgresql/vector.so"
cp "${VECTOR}/vector.control" "${SHARE_EXT}/"
cp "${VECTOR}/sql/vector.sql" "${SHARE_EXT}/vector--0.8.0.sql"

# PGSRC is only exported by build-pgcore.sh; resume builds skip that script,
# so search the usual locations as well.
PGSRC_REAL=""
for candidate in "${PGSRC:-}" "${WORKSPACE}/postgresql-${PG_BRANCH}" \
                 "${WORKSPACE}/postgresql"; do
    if [ -n "${candidate}" ] && [ -d "${candidate}/contrib" ]; then
        PGSRC_REAL="${candidate}"
        break
    fi
done
if [ -z "${PGSRC_REAL}" ]; then
    echo "postgresql source tree not found (PGSRC=${PGSRC:-unset} WORKSPACE=${WORKSPACE:-unset})"
    exit 23
fi

SQL_FILES=("${SHARE_EXT}/vector--0.8.0.sql")
MODULE_COUNT=0

for contrib_mod in $(grep -v '^#' "${CONTRIB_LIST}" | tr -d '\r'); do
    [ -n "${contrib_mod}" ] || continue
    contrib_src="${PGSRC_REAL}/contrib/${contrib_mod}"
    if [ ! -d "${contrib_src}" ]; then
        echo "contrib module not found: ${contrib_mod}"
        exit 22
    fi
    # Some modules ship a bison parser and a flex scanner (seg, cube).
    for yacc_src in "${contrib_src}"/*.y; do
        [ -f "${yacc_src}" ] || continue
        yacc_out="${yacc_src%.y}.c"
        if [ ! -f "${yacc_out}" ]; then
            ( cd "${contrib_src}" && bison -d -o "$(basename "${yacc_out}")" \
                "$(basename "${yacc_src}")" )
        fi
    done
    for lex_src in "${contrib_src}"/*.l; do
        [ -f "${lex_src}" ] || continue
        lex_out="${lex_src%.l}.c"
        if [ ! -f "${lex_out}" ]; then
            ( cd "${contrib_src}" && flex -o "$(basename "${lex_out}")" \
                "$(basename "${lex_src}")" )
        fi
    done
    # The library name can differ from the directory (intarray ships _int).
    module_lib=$(sed -n "s/.*module_pathname *= *'[^/]*\/\([^']*\)'.*/\1/p" \
        "${contrib_src}/${contrib_mod}.control" | head -1)
    [ -n "${module_lib}" ] || module_lib="${contrib_mod}"
    touch "${PGROOT}/lib/postgresql/${module_lib}.so"
    cp "${contrib_src}/${contrib_mod}.control" "${SHARE_EXT}/"
    for contrib_sql in "${contrib_src}"/*.sql; do
        [ -f "${contrib_sql}" ] || continue
        cp "${contrib_sql}" "${SHARE_EXT}/"
        SQL_FILES+=("${SHARE_EXT}/$(basename "${contrib_sql}")")
    done
    case "${contrib_mod}" in
        fuzzystrmatch)
            # daitch_mokotoff.h is generated by a Perl script in the module;
            # the container has perl, and a pre-generated copy ships with the
            # repository as a fallback.
            if [ ! -f "${contrib_src}/daitch_mokotoff.h" ]; then
                if command -v perl >/dev/null 2>&1; then
                    perl "${contrib_src}/daitch_mokotoff_header.pl" \
                        "${contrib_src}/daitch_mokotoff.h"
                else
                    cp "${WORKSPACE}/extra/fuzzystrmatch/daitch_mokotoff.h" \
                        "${contrib_src}/daitch_mokotoff.h"
                fi
            fi
            ;;
        unaccent)
            mkdir -p "${PGROOT}/share/postgresql/tsearch_data"
            cp "${contrib_src}/unaccent.rules" \
                "${PGROOT}/share/postgresql/tsearch_data/"
            ;;
    esac
    MODULE_COUNT=$((MODULE_COUNT + 1))
done

python3 wasm-build/gen_extension_symbols.py \
    "${WORKSPACE}/wasm-build/sdk_port-wasi/extension_symbols.h" \
    "${SQL_FILES[@]}"

echo "static extensions: installed vector and ${MODULE_COUNT} contrib modules, generated symbol table"
