def test_prepared_statement_reuse(conn: object) -> None:
    cursor = conn.cursor()
    for value in range(10):
        cursor.execute("select %s::int * 3 as n", (value,), prepare=True)
        assert cursor.fetchone() == (value * 3,)
    conn.rollback()


def test_two_connections_transaction_pinning(server: PGliteServer) -> None:
    import threading
    import time

    with psycopg.connect(server.dsn) as first, psycopg.connect(server.dsn) as second:
        first.execute("create table pinned (n int)")
        first.commit()
        # Leave an open transaction on the first connection: it now owns the
        # single backend until commit or rollback.
        first.execute("insert into pinned values (1)")

        outcome: dict[str, str] = {}

        def writer() -> None:
            try:
                second.execute("insert into pinned values (2)")
                second.commit()
                outcome["result"] = "ok"
            except Exception as exc:  # noqa: BLE001
                outcome["result"] = repr(exc)

        thread = threading.Thread(target=writer)
        thread.start()
        time.sleep(0.2)
        # Nothing else may run until the first connection ends its transaction.
        assert outcome == {}
        first.commit()
        thread.join(timeout=15)
        assert outcome.get("result") == "ok"
        assert first.execute("select count(*) from pinned").fetchone() == (2,)
        first.rollback()


