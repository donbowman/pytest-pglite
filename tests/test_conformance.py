def test_rich_types(conn: object) -> None:
    conn.execute(
        "create table typed ("
        "  id bigint generated by default as identity primary key,"
        "  flag boolean,"
        "  price numeric(10, 2),"
        "  payload jsonb,"
        "  tags text[],"
        "  blob bytea,"
        "  created timestamptz,"
        "  span interval,"
        "  uid uuid"
        ")"
    )
    conn.execute(
        "insert into typed (flag, price, payload, tags, blob, created, span, uid)"
        " values (%s, %s, %s, %s, %s, %s, %s, %s)",
        (
            True,
            "12.34",
            Jsonb({"a": [1, 2]}),
            ["x", "y"],
            b"\x00\x01",
            "2026-01-02T03:04:05+00:00",
            "1 day 02:03:00",
            "11111111-2222-3333-4444-555555555555",
        ),
    )
    row = conn.execute(
        "select flag, price, payload->'a'->>1, tags[1], blob, span, uid from typed"
    ).fetchone()
    assert row[0] is True
    assert str(row[1]) == "12.34"
    assert row[2] == "2"
    assert row[3] == "x"
    assert row[4] == b"\x00\x01"
    assert row[5] == timedelta(days=1, hours=2, minutes=3)
    assert str(row[6]) == "11111111-2222-3333-4444-555555555555"
    conn.rollback()


def test_cursors(conn: object) -> None:
    conn.execute("create table cursor_demo (n int)")
    conn.execute("insert into cursor_demo select generate_series(1, 10)")
    conn.commit()
    conn.execute("declare c cursor for select n from cursor_demo order by n")
    rows = conn.execute("fetch 3 from c").fetchall()
    assert rows == [(1,), (2,), (3,)]
    conn.execute("close c")
    conn.rollback()


def test_large_result_overflows_cma(conn: object) -> None:
    # The reply buffer is a few megabytes; a large result spills to the socket
    # file path inside the preopened filesystem, which the engine must drain.
    row = conn.execute(
        "select count(*), sum(n) from (select generate_series(1, 400000) as n) s"
    ).fetchone()
    assert row == (400000, 80000200000)
    conn.rollback()


def test_copy_to_stdout(conn: object) -> None:
    conn.execute("create table copy_out (id int, name text)")
    conn.execute(
        "insert into copy_out select n, 'row-' || n from generate_series(1, 500) n"
    )
    conn.commit()
    with conn.cursor().copy("copy copy_out to stdout") as copy:
        rows = list(copy.rows())
    # COPY TO STDOUT is textual; values arrive as strings.
    assert rows[0] == ("1", "row-1")
    assert len(rows) == 500
    conn.rollback()


def test_copy_from_stdin_is_reported_cleanly(conn: object) -> None:
    # The libpglite CMA transport cannot stream CopyData into a synchronous
    # CopyFrom; the proxy answers 0A000 instead of wedging the backend.
    conn.execute("create table copy_in (id int, name text)")
    conn.commit()
    with pytest.raises(psycopg.errors.FeatureNotSupported) as excinfo:
        with conn.cursor().copy("copy copy_in from stdin") as copy:
            copy.write_row((1, "a"))
    assert excinfo.value.sqlstate == "0A000"
    conn.rollback()
    assert conn.execute("select 1 as alive").fetchone() == (1,)
    conn.rollback()


