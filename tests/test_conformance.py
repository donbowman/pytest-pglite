def test_error_sqlstates(conn: object) -> None:
    conn.execute(
        "create table errors (id int primary key, tag text not null check (tag <> ''))"
    )
    conn.execute("insert into errors values (1, 'ok')")
    conn.commit()

    cases: list[tuple[str, tuple[object, ...], str]] = [
        ("insert into errors values (1, 'dup')", (), "23505"),
        ("insert into errors values (2, null)", (), "23502"),
        ("insert into errors values (3, '')", (), "23514"),
        ("select 1/0", (), "22012"),
        ("select * from missing", (), "42P01"),
        ("syntax error here", (), "42601"),
        ("insert into errors values ('not-an-int', 'x')", (), "22P02"),
    ]
    for sql, params, expected in cases:
        with pytest.raises(psycopg.Error) as excinfo:
            conn.execute(sql, params or None)
        assert excinfo.value.sqlstate == expected, sql
        conn.rollback()
        assert conn.execute("select 1 as alive").fetchone() == (1,)
        conn.rollback()


def test_sequences_and_temp_tables(conn: object) -> None:
    conn.execute("create sequence seq_test start 42")
    assert conn.execute("select nextval('seq_test')").fetchone() == (42,)
